export async function testConnection(): Promise<boolean> {
  try {
    await getDocFromServer(doc(db, 'test', 'connection'));
    return true;
  } catch (error) {
    if (error instanceof Error && error.message.includes('the client is offline')) {
      console.warn('Firestore is running in offline mode. Please verify network configuration.');
    } else {
      console.warn('Initial Firestore connectivity check status:', error);
    }
    return false;
  }
}

// Execute connection test on boot
testConnection();
